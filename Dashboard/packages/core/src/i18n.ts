/** Översätter inbyggda metric-namn; egna metrics (custom_…) behåller byråns namn. */
export function metricText(id: string, sv: { label: string; shortLabel?: string }, lang: Lang = "sv"): { label: string; shortLabel?: string } {
  if (lang === "sv") return sv;
  const en = METRIC_EN[id as MetricId];
  return en ? { label: en.label, shortLabel: en.short } : sv;
}

export const dimensionText = (id: DimensionId, sv: string, lang: Lang = "sv") => (lang === "en" ? (DIMENSION_EN[id] ?? sv) : sv);

